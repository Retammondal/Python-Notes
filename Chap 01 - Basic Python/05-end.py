# end use in Print
print("1st Line")
print("2nd Line")
print("3rd Line")

# print() call invisibly appends a “newline” (like hitting Enter). 
# You can override this using the end keyword parameter:
print("\nUsing end parameter in Print Statement")
print("Hello", end="-")
print("World")

# end=" " ; replaces the Enter key with a blank space
# end="#" ; replaces the Enter key with #
print("Retam", end=" ")
print("Mondal",end=" #")
print(1)
print("This starts from new line")