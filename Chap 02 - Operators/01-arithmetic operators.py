# Addition, Multiplication , Substraction
print(5+4)
print(4-8)
print(10*3)
print(5.3+2.3) # Results in Float
print(5.2*5) # Results in Float
print(20-2.3)
print("---------------------------------")

# True Division
print(10/3) #Ans is in float
print(12/3) #Still Ans will be in float
print("---------------------------------")



# Floored Division
print(20//6)
print(10//5) #will give ans in Integer
print(10/5) #Will give ans in float
print("---------------------------------")



# Modulas Operator
a=10//3
b=10%3
print("Quotient :",a)
print("Remainder :",b)
c=10.0//3
d=10.0%3
print("Quotient :",c)
print("Remainder :",d)
print("---------------------------------")



# Power Operator
print(2**3, type(2**3))
print(2.3**3, type(2.3**3)) #If even one number is a Float, the result becomes a Float; otherwise Integer