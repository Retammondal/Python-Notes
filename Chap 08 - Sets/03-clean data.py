
# -----------------------------------------------------------------------
# Convert List to Set   --> Unique Datas will come
# -----------------------------------------------------------------------

list_ex = ["Retam", "Retam", "Mondal", 34, 24.5]
set_of_list = set(list_ex)
print(set_of_list)

# -----------------------------------------------------------------------
# Convert String to Set   --> Unique Characters of String will come
# -----------------------------------------------------------------------

str_ex = "Retam Mondal"
set_of_str = set(str_ex)
print(set_of_str)